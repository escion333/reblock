import type { VercelRequest, VercelResponse } from '@vercel/node'
import { getArenaAccessToken } from './_arenaAuth'

type ResearchResult = {
  title: string
  channelSlug: string
  summary: string
  blocks: Array<{
    title: string
    body: string
    sourceUrls: string[]
  }>
  sourceLinks: Array<{
    title: string
    url: string
    note: string
  }>
  imageQueries: string[]
}

type ArenaChannel = {
  id: number | string
  slug: string
  title: string
  owner?: { slug?: string }
  user?: { slug?: string }
  _links?: { html?: { href?: string } }
}

type ArenaImage = {
  title?: string
  image?: {
    src?: string
    display?: { url?: string }
    original?: { url?: string }
  }
}

const ARENA_API = 'https://api.are.na'

export default async function handler(request: VercelRequest, response: VercelResponse) {
  if (request.method !== 'POST') {
    response.setHeader('Allow', 'POST')
    return response.status(405).json({ error: 'Method not allowed.' })
  }

  const apiKey = getArenaAccessToken(request)
  if (!apiKey) {
    return response.status(401).json({ error: 'Connect Are.na before publishing.' })
  }

  const research = request.body?.research as ResearchResult | undefined
  if (!isResearch(research)) {
    return response.status(400).json({ error: 'Structured research payload is required.' })
  }

  try {
    const channel = await createChannel(apiKey, research)
    const textBlocks = buildTextBlocks(research)
    const links = await collectVerifiedSourceLinks(research.sourceLinks)
    const linkBlocks = links.map((link) => ({
      value: link.url,
      title: link.title,
    }))
    const images = await collectArenaImages(apiKey, research)
    const imageBlocks = images.slice(0, 6).map((image) => ({
      value: image.url,
      title: image.title || research.title,
      alt_text: image.title || `${research.title} reference image`,
      channel_ids: [channel.id],
    }))

    console.info(
      JSON.stringify({
        event: 'arena_publish_counts',
        title: research.title,
        textBlocks: textBlocks.length,
        verifiedLinks: linkBlocks.length,
        imageQueries: research.imageQueries,
        imagesFound: images.length,
        imagesPublished: imageBlocks.length,
      }),
    )

    await createBlocks(apiKey, [...textBlocks, ...linkBlocks, ...imageBlocks], channel.id)

    return response.status(200).json({
      channelUrl: channelUrl(channel),
      channelSlug: channel.slug,
      blockCount: textBlocks.length,
      linkCount: linkBlocks.length,
      imageCount: imageBlocks.length,
    })
  } catch (error) {
    return response.status(500).json({
      error: error instanceof Error ? error.message : 'Unexpected Are.na error.',
    })
  }
}

function isResearch(value: unknown): value is ResearchResult {
  if (!value || typeof value !== 'object') {
    return false
  }

  const candidate = value as ResearchResult
  return (
    typeof candidate.title === 'string' &&
    typeof candidate.channelSlug === 'string' &&
    typeof candidate.summary === 'string' &&
    Array.isArray(candidate.blocks) &&
    Array.isArray(candidate.imageQueries)
  )
}

async function createChannel(apiKey: string, research: ResearchResult): Promise<ArenaChannel> {
  const description = `Generated by reBlock.\n\n${research.summary}`
  const v3 = await arenaFetch(apiKey, '/v3/channels', {
    method: 'POST',
    body: JSON.stringify({
      title: research.title,
      slug: uniqueSlug(research.channelSlug),
      description,
      visibility: 'closed',
    }),
  })

  if (v3.ok) {
    return (await v3.json()) as ArenaChannel
  }

  const v2 = await arenaFetch(apiKey, '/v2/channels', {
    method: 'POST',
    body: JSON.stringify({
      title: research.title,
      status: 'closed',
    }),
  })

  if (!v2.ok) {
    const payload = await v2.text()
    throw new Error(payload || 'Could not create Are.na channel.')
  }

  return (await v2.json()) as ArenaChannel
}

function buildTextBlocks(research: ResearchResult) {
  const intro = {
    value: `# ${research.title}\n\n${research.summary}`,
    title: 'Overview',
  }

  const blocks = research.blocks.map((block) => ({
    value:
      block.sourceUrls.length > 0
        ? `## ${block.title}\n\n${block.body}\n\nSources:\n${block.sourceUrls.map((url) => `- ${url}`).join('\n')}`
        : `## ${block.title}\n\n${block.body}`,
    title: block.title,
  }))

  return [intro, ...blocks]
}

async function collectVerifiedSourceLinks(sources: ResearchResult['sourceLinks']) {
  const links: Array<{ url: string; title: string }> = []
  const seen = new Set<string>()

  for (const source of sources.slice(0, 10)) {
    if (!source.url || seen.has(source.url) || !(await isReachableUrl(source.url))) {
      continue
    }

    seen.add(source.url)
    links.push({
      url: source.url,
      title: source.title || source.url,
    })
  }

  return links
}

async function collectArenaImages(apiKey: string, research: ResearchResult) {
  const images: Array<{ url: string; title?: string }> = []
  const seen = new Set<string>()
  const queries = unique([
    ...research.imageQueries,
    research.title,
    ...research.blocks.map((block) => block.title),
  ])

  for (const query of queries.slice(0, 10)) {
    const params = new URLSearchParams({ query, type: 'Image', per: '12' })
    const result = await arenaFetch(apiKey, `/v3/search?${params.toString()}`)

    if (!result.ok) {
      console.info(
        JSON.stringify({
          event: 'arena_image_search_failed',
          query,
          status: result.status,
        }),
      )
      continue
    }

    const payload = (await result.json()) as { data?: ArenaImage[] }
    const results = payload.data ?? []
    console.info(
      JSON.stringify({
        event: 'arena_image_search_results',
        query,
        results: results.length,
      }),
    )
    for (const item of results) {
      const url = findCloudfrontImageUrl(item)
      if (url && !seen.has(url)) {
        seen.add(url)
        images.push({ url, title: item.title })
      }
    }
  }

  return images
}

function findCloudfrontImageUrl(image: ArenaImage) {
  const candidates = [
    image.image?.src,
    image.image?.display?.url,
    image.image?.original?.url,
  ].filter(Boolean) as string[]

  return candidates.find((url) => url.includes('cloudfront.net')) ?? candidates[0]
}

async function createBlocks(
  apiKey: string,
  blocks: Array<Record<string, unknown>>,
  channelId: string | number,
) {
  const chunks = chunk(blocks, 4)

  for (const group of chunks) {
    await Promise.all(
      group.map(async (block) => {
        const result = await arenaFetch(apiKey, '/v3/blocks', {
          method: 'POST',
          body: JSON.stringify({
            ...block,
            channel_ids: [channelId],
          }),
        })

        if (!result.ok) {
          const payload = await result.text()
          throw new Error(payload || 'Could not create Are.na block.')
        }
      }),
    )
  }
}

function arenaFetch(apiKey: string, path: string, init: RequestInit = {}) {
  return fetch(`${ARENA_API}${path}`, {
    ...init,
    headers: {
      accept: 'application/json',
      authorization: `Bearer ${apiKey}`,
      'content-type': 'application/json',
      ...init.headers,
    },
  })
}

async function isReachableUrl(url: string) {
  try {
    const head = await fetch(url, {
      method: 'HEAD',
      redirect: 'follow',
      signal: AbortSignal.timeout(5000),
    })

    if (head.status >= 200 && head.status < 400) {
      return true
    }

    if (head.status !== 403 && head.status !== 405) {
      return false
    }

    const get = await fetch(url, {
      method: 'GET',
      redirect: 'follow',
      signal: AbortSignal.timeout(5000),
    })

    return get.status >= 200 && get.status < 400
  } catch {
    return false
  }
}

function uniqueSlug(slug: string) {
  return `${slug}-${Date.now().toString(36)}`
}

function channelUrl(channel: ArenaChannel) {
  if (channel._links?.html?.href) {
    return channel._links.html.href
  }

  const ownerSlug = channel.owner?.slug ?? channel.user?.slug
  if (ownerSlug) {
    return `https://www.are.na/${ownerSlug}/${channel.slug}`
  }

  return `https://www.are.na/channel/${channel.slug}`
}

function chunk<T>(items: T[], size: number) {
  const chunks: T[][] = []
  for (let index = 0; index < items.length; index += size) {
    chunks.push(items.slice(index, index + size))
  }

  return chunks
}

function unique(values: string[]) {
  return Array.from(new Set(values.map((value) => value.trim()).filter(Boolean)))
}
